export function getSheetCategories(sheetId: DSASheetId): SheetCategory[] {
  const filtered = ALL_SHEET_PROBLEMS.filter((p) => p.sheets.includes(sheetId));

  // Canonical 18 Category Order from NeetCode 150
  const categoryOrder = [
    "Arrays & Hashing",
    "Two Pointers",
    "Sliding Window",
    "Stack",
    "Binary Search",
    "Linked List",
    "Trees",
    "Tries",
    "Heap / Priority Queue",
    "Backtracking",
    "Graphs",
    "Advanced Graphs",
    "1-D Dynamic Programming",
    "2-D Dynamic Programming",
    "Greedy",
    "Intervals",
    "Math & Geometry",
    "Bit Manipulation",
  ];

  const map = new Map<string, SheetProblem[]>();
  for (const cat of categoryOrder) {
    map.set(cat, []);
  }

  for (const prob of filtered) {
    const list = map.get(prob.category) || [];
    list.push(prob);
    map.set(prob.category, list);
  }

  const result: SheetCategory[] = [];
  for (const [name, problems] of map.entries()) {
    if (problems.length > 0) {
      result.push({
        name,
        description: `${problems.length} problems`,
        problems,
      });
    }
  }

  return result;
}
